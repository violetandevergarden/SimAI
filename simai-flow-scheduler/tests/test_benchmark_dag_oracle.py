"""Tests for stage-1 benchmark generation and exact scheduling oracles."""

import json
from pathlib import Path

from scripts.benchmark_dag_oracle import (
    BenchmarkDAG,
    BenchTask,
    POLICIES,
    adversarial_benchmarks,
    branch_and_bound_oracle,
    contract_compute_chains,
    dag_from_json,
    dag_to_json,
    exact_oracle,
    heuristic_schedule,
    llm_motif_benchmarks,
    lower_bounds,
    reduce_effective_dag,
)


ROOT = Path(__file__).resolve().parents[1]


def test_exact_oracles_agree_on_known_counterexample() -> None:
    dag = next(
        dag for dag in adversarial_benchmarks()
        if dag.name == "longest_tail_counterexample"
    )

    dynamic_programming = exact_oracle(dag)
    branch_and_bound = branch_and_bound_oracle(dag)

    assert dynamic_programming.makespan == 8
    assert branch_and_bound.makespan == 8
    assert dynamic_programming.lower_bounds["combined"] == 8


def test_every_catalog_benchmark_has_valid_bounds_and_schedules() -> None:
    catalog = [*adversarial_benchmarks(), *llm_motif_benchmarks()]

    assert len(adversarial_benchmarks()) == 7
    assert len(llm_motif_benchmarks()) == 7
    for dag in catalog:
        assert dag.validate() == []
        optimum = exact_oracle(dag).makespan
        assert branch_and_bound_oracle(dag).makespan == optimum
        assert lower_bounds(dag)["combined"] <= optimum
        for policy in POLICIES:
            makespan, decisions = heuristic_schedule(dag, policy)
            assert makespan >= optimum
            assert len(decisions) == makespan


def test_compute_chain_contraction_preserves_optimum() -> None:
    dag = BenchmarkDAG(
        "contract",
        "test",
        (
            BenchTask("flow", "comm", 2),
            BenchTask("compute1", "compute", 3, ("flow",)),
            BenchTask("compute2", "compute", 4, ("compute1",)),
            BenchTask("tail_flow", "comm", 1, ("compute2",)),
        ),
    )
    contracted = contract_compute_chains(dag)

    assert len(contracted.tasks) == 3
    assert exact_oracle(contracted).makespan == exact_oracle(dag).makespan


def test_benchmark_json_round_trip_is_stable() -> None:
    dag = adversarial_benchmarks()[0]

    restored = dag_from_json(dag_to_json(dag))

    assert restored == dag
    assert exact_oracle(restored).makespan == exact_oracle(dag).makespan


def test_real_effective_dag_reduction_is_small_and_exactly_solvable() -> None:
    path = ROOT / "outputs/dag_audit/1f1b/effective_dag.json"
    if not path.exists():
        # The repository output is generated by stage 0 and may be gitignored.
        return
    graph = json.loads(path.read_text(encoding="utf-8"))
    reduced = reduce_effective_dag(graph, max_flows=4, quantum_us=500)

    assert reduced.category == "real_reduction"
    assert len(reduced.tasks) < len(graph["nodes"])
    assert sum(task.kind == "comm" for task in reduced.tasks) <= 24
    dp = exact_oracle(reduced)
    bnb = branch_and_bound_oracle(reduced)
    assert dp.makespan == bnb.makespan
    assert dp.lower_bounds["combined"] <= dp.makespan
